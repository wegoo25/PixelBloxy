/* ============================================================
   PRODUCT GALLERY
   ============================================================ */

function renderGallery(product) {

    const mainImage =
        document.getElementById("main-image");

    const thumbnailContainer =
        document.getElementById("thumbnail-container");

    if (!mainImage) {
        return;
    }


    /*
     * Main image
     */

    mainImage.src =
        product.images[0];

    mainImage.alt =
        product.title;

    mainImage.loading =
        "eager";


    /*
     * Thumbnails
     */

    if (!thumbnailContainer) {
        return;
    }

    thumbnailContainer.innerHTML =
        product.images.map((image, index) => `
            <img
                src="${image}"
                alt="${escapeHtml(product.title)} - Image ${index + 1}"
                class="product-gallery-thumb ${
                    index === 0 ? "active" : ""
                } rounded-xl w-full h-24 object-cover"
                data-index="${index}"
                loading="lazy"
            >
        `).join("");


    /*
     * Thumbnail click
     */

    thumbnailContainer
        .querySelectorAll(".product-gallery-thumb")
        .forEach(thumb => {

            thumb.addEventListener(
                "click",
                function () {

                    mainImage.src =
                        this.src;

                    mainImage.alt =
                        this.alt;

                    thumbnailContainer
                        .querySelectorAll(
                            ".product-gallery-thumb"
                        )
                        .forEach(t =>
                            t.classList.remove("active")
                        );

                    this.classList.add("active");
                }
            );
        });
}


/* ============================================================
   RELATED PRODUCTS
   ============================================================ */

async function renderRelatedProducts(currentProduct) {

    const grid =
        document.getElementById(
            "related-products-grid"
        );

    if (!grid) {
        return;
    }

    /*
     * First try products already loaded by shopify.js.
     */

    let relatedProducts = [];

    if (
        typeof PRODUCTS !== "undefined" &&
        Array.isArray(PRODUCTS) &&
        PRODUCTS.length
    ) {

        relatedProducts =
            PRODUCTS
                .filter(product =>
                    product.handle !== currentProduct.handle
                )
                .filter(product => {

                    /*
                     * Prefer products from the same category.
                     */

                    if (
                        currentProduct.categoryHandle &&
                        product.categories?.includes(
                            currentProduct.categoryHandle
                        )
                    ) {
                        return true;
                    }

                    return false;
                })
                .slice(0, 4);
    }


    /*
     * If the Shopify.js data isn't available or there aren't
     * enough same-category products, fetch related products.
     */

    if (relatedProducts.length < 4) {

        try {

            const data =
                await shopifyProductRequest(`
                    {
                        products(first: 20) {
                            edges {
                                node {
                                    id
                                    title
                                    handle
                                    featuredImage {
                                        url
                                        altText
                                    }
                                    collections(first: 5) {
                                        edges {
                                            node {
                                                handle
                                                title
                                            }
                                        }
                                    }
                                    variants(first: 1) {
                                        edges {
                                            node {
                                                id
                                                availableForSale
                                                price {
                                                    amount
                                                }
                                                compareAtPrice {
                                                    amount
                                                }
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                `);

            const fetched =
                data.products.edges
                    .map(edge => edge.node)
                    .filter(product =>
                        product.handle !==
                        currentProduct.handle
                    )
                    .filter(product => {

                        if (
                            !currentProduct.categoryHandle
                        ) {
                            return true;
                        }

                        return product.collections.edges
                            .some(edge =>
                                edge.node.handle ===
                                currentProduct.categoryHandle
                            );
                    })
                    .map(product => {

                        const variant =
                            product.variants.edges[0]?.node;

                        if (!variant) {
                            return null;
                        }

                        return {
                            id: product.id,
                            title: product.title,
                            handle: product.handle,

                            image:
                                product.featuredImage?.url ||
                                "placeholder.png",

                            price:
                                Number(
                                    variant.price.amount
                                ),

                            compareAtPrice:
                                variant.compareAtPrice?.amount
                                    ? Number(
                                        variant.compareAtPrice.amount
                                    )
                                    : null,

                            variantId:
                                variant.id,

                            available:
                                variant.availableForSale,

                            categories:
                                product.collections.edges.map(
                                    edge =>
                                        edge.node.handle
                                )
                        };
                    })
                    .filter(Boolean);

            /*
             * Combine existing and fetched products without
             * duplicates.
             */

            const combined = [
                ...relatedProducts,
                ...fetched
            ];

            const seen = new Set();

            relatedProducts =
                combined
                    .filter(product => {

                        if (!product.handle) {
                            return false;
                        }

                        if (seen.has(product.handle)) {
                            return false;
                        }

                        seen.add(product.handle);

                        return true;
                    })
                    .slice(0, 4);

        } catch (error) {

            console.error(
                "Failed to load related products:",
                error
            );
        }
    }


    /*
     * If there are still no related products, show a message.
     */

    if (!relatedProducts.length) {

        grid.innerHTML = `
            <div class="col-span-full text-center py-10 text-soft">
                No related products found.
            </div>
        `;

        return;
    }


    /*
     * Render related products.
     */

    grid.innerHTML =
        relatedProducts.map(product => {

            const image =
                product.image ||
                product.images?.[0] ||
                "placeholder.png";

            const title =
                product.title ||
                "Product";

            const productUrl = product.handle
                ? `product.html?handle=${encodeURIComponent(product.handle)}`
                : `product.html?id=${encodeURIComponent(product.id)}`;

            const price =
                Number(product.price || 0);

            const compareAt =
                product.compareAtPrice;

            const hasDiscount =
                compareAt &&
                compareAt > price;

            const discount =
                hasDiscount
                    ? Math.round(
                        (1 - price / compareAt) * 100
                    )
                    : 0;

            return `
                <article class="item-card p-4 reveal product-page-related-card">
                    <div class="product-related-image-wrap relative overflow-hidden rounded-xl">
                        <a href="${productUrl}">
                            <img
                                src="${image}"
                                alt="${escapeHtml(title)}"
                                class="product-related-image rounded-xl mb-4 w-full h-48 object-cover"
                                loading="lazy"
                            >
                        </a>
                        ${
                            hasDiscount
                                ? `<span class="discount-badge">${discount}% OFF</span>`
                                : ""
                        }
                    </div>
                    <h3 class="font-semibold text-lg" title="${escapeHtml(title)}">
                        <a href="${productUrl}" class="text-inherit no-underline hover:text-violet">${escapeHtml(title)}</a>
                    </h3>
                    <div class="product-related-price-row mt-2">
                        <div>
                        <span class="text-violet font-bold">$${price.toFixed(2)}</span>
                        ${
                            hasDiscount
                                ? `<span class="text-soft text-sm line-through ml-2">$${compareAt.toFixed(2)}</span>`
                                : ""
                        }
                        </div>
                        ${window.productWishlistButtonMarkup?.(product) || ""}
                    </div>
                </article>
            `;
        }).join("");
}


/* ============================================================
   NOT FOUND
   ============================================================ */

function showProductNotFound(message = "Product not found.") {

    const content =
        document.getElementById(
            "product-content"
        );

    const notFound =
        document.getElementById(
            "product-not-found"
        );

    if (content) {
        content.style.display =
            "none";
    }

    if (notFound) {

        notFound.classList.remove(
            "hidden"
        );

        const paragraph =
            notFound.querySelector("p");

        if (paragraph) {
            paragraph.textContent =
                message;
        }
    }

    document.title =
        "Product Not Found — PixelBloxy";
}


/* ============================================================
   CART — SHOPIFY
   ============================================================ */

async function addProductToShopifyCart(
    variantId,
    quantity = 1
) {
    let added = false;
    let updatedCart = null;
    PRODUCT_CART_ID =
        localStorage.getItem("shopify_cart") || null;

    if (!variantId) {

        showToast(
            "Error",
            "This product cannot be added to the cart."
        );

        return false;
    }

    try {

        /*
         * Create a cart if one doesn't exist.
         */

        const cartSelection = `
            totalQuantity
            cost {
                subtotalAmount { amount currencyCode }
            }
            lines(first: 100) {
                edges {
                    node {
                        id
                        quantity
                        cost {
                            totalAmount { amount currencyCode }
                        }
                        merchandise {
                            ... on ProductVariant {
                                id
                                title
                                product { title }
                                image { url }
                                price { amount currencyCode }
                            }
                        }
                    }
                }
            }
        `;

        if (!PRODUCT_CART_ID) {
            const createData = await shopifyProductRequest(`
                mutation CreateCartWithLine(
                    $variantId: ID!,
                    $quantity: Int!
                ) {
                    cartCreate(input: {
                        lines: [{
                            merchandiseId: $variantId,
                            quantity: $quantity
                        }]
                    }) {
                        cart {
                            id
                            ${cartSelection}
                        }
                        userErrors { field message }
                    }
                }
            `, { variantId, quantity });

            const createResult = createData.cartCreate;
            if (createResult.userErrors?.length) {
                throw new Error(
                    createResult.userErrors.map(error => error.message).join(", ")
                );
            }
            updatedCart = createResult.cart;
            PRODUCT_CART_ID = updatedCart?.id;
            if (!PRODUCT_CART_ID) {
                throw new Error("Shopify couldn't create a cart.");
            }
            localStorage.setItem("shopify_cart", PRODUCT_CART_ID);
        } else {
            const addData =
                await shopifyProductRequest(`
                mutation AddToCart(
                    $cartId: ID!,
                    $variantId: ID!,
                    $quantity: Int!
                ) {
                cartLinesAdd(
                        cartId: $cartId
                        lines: [
                            {
                                merchandiseId: $variantId
                                quantity: $quantity
                            }
                        ]
                    ) {
                        cart { ${cartSelection} }
                        userErrors { field message }
                    }
                }
            `, {
                cartId: PRODUCT_CART_ID,
                variantId,
                quantity
            });

            const errors = addData.cartLinesAdd.userErrors;
            if (errors?.length) {
            throw new Error(
                errors.map(error => error.message).join(", ")
            );
            }
            updatedCart = addData.cartLinesAdd.cart;
            if (!updatedCart) {
            throw new Error("Shopify couldn't add this item to your cart.");
            }
        }
        added = true;

        const addedLine = updatedCart.lines?.edges
            .find(({ node }) => node.merchandise?.id === variantId)?.node;
        const stockLimited = addedLine && addedLine.quantity < quantity;

        if (typeof renderCartItems === "function") {
            renderCartItems(updatedCart);
        }

        showToast(
            stockLimited ? "Stock limit reached" : "Added to Cart",
            stockLimited
                ? `Only ${addedLine.quantity} available for this product.`
                : `${CURRENT_PRODUCT?.title || "Product"} added to your cart.`
        );


        /*
         * Open the existing cart drawer.
         */

        if (
            typeof openCart ===
            "function"
        ) {

            openCart();

        } else {

            const cart =
                document.getElementById("cart");

            const overlay =
                document.getElementById(
                    "cart-overlay"
                );

            cart?.classList.add("active");
            overlay?.classList.add("active");

            document.body.style.overflow =
                "hidden";
        }


        return true;

    } catch (error) {

        console.error(
            "Add to Shopify cart error:",
            error
        );

        /*
         * If the saved cart is invalid/expired,
         * remove it so a fresh cart can be created.
         */

        if (
            error.message
                ?.toLowerCase()
                .includes("cart")
        ) {

            localStorage.removeItem(
                "shopify_cart"
            );

            PRODUCT_CART_ID = null;
        }

        showToast(
            added ? "Cart Refresh Error" : "Cart Error",
            added
                ? "Item added, but the cart display couldn't refresh."
                : error.message || "We couldn't add this item to your cart."
        );

        return false;
    }
}


/* ============================================================
   HTML ESCAPE HELPER
   ============================================================ */

function escapeHtml(value) {

    return String(value ?? "")
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#039;");
}


/* ============================================================
   QUANTITY CONTROLS
   ============================================================ */

function setupQuantityControls() {

    const decrease =
        document.getElementById(
            "quantity-decrease"
        );

    const increase =
        document.getElementById(
            "quantity-increase"
        );

    const input =
        document.getElementById(
            "quantity-input"
        );


    decrease?.addEventListener(
        "click",
        () => {

            if (!input) {
                return;
            }

            let value =
                parseInt(input.value) || 1;

            if (value > 1) {
                value--;
            }

            input.value =
                value;
            syncProductStockControls();
        }
    );


    increase?.addEventListener(
        "click",
        () => {

            if (!input) {
                return;
            }

            let value =
                parseInt(input.value) || 1;

            const max = Number(input.max) || 99;
            if (value < max) {
                value++;
            }

            input.value =
                value;
            syncProductStockControls();
        }
    );


    input?.addEventListener(
        "change",
        () => {

            let value =
                parseInt(input.value);

            if (isNaN(value) || value < 1) {
                value = 1;
            }

            const max = Number(input.max) || 99;
            if (value > max) {
                value = max;
            }

            input.value =
                value;
            syncProductStockControls();
        }
    );
}


