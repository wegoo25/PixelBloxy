/* ============================================================
   LOAD PRODUCT
   ============================================================ */

async function loadProductPage() {

    const params =
        new URLSearchParams(window.location.search);

    /*
     * Support both URL formats.
     *
     * Current shopify.js:
     * product.html?id=gid://shopify/Product/123
     *
     * New format:
     * product.html?handle=golden-unicorn-pet
     */

    const handle =
        params.get("handle");

    const id =
        params.get("id");


    /*
     * We need either an ID or a handle.
     */

    if (!handle && !id) {

        showProductNotFound(
            "No product was specified."
        );

        return;
    }


    /*
     * Load product from Shopify.
     */

    try {

        const rawProduct =
            await getShopifyProduct({
                handle,
                id
            });


        if (!rawProduct) {

            showProductNotFound(
                "This product could not be found in Shopify."
            );

            return;
        }


        /*
         * Convert Shopify data into the format
         * used by the product page.
         */

        const product =
            normalizeShopifyProduct(
                rawProduct
            );


        if (!product) {

            showProductNotFound(
                "This product has no purchasable variant."
            );

            return;
        }


        /*
         * Render everything.
         */

        renderProduct(product);


        /*
         * Show the product page.
         */

        const content =
            document.getElementById(
                "product-content"
            );

        if (content) {
            content.style.display = "";
        }


        /*
         * Hide the not-found screen if it
         * was previously displayed.
         */

        const notFound =
            document.getElementById(
                "product-not-found"
            );

        if (notFound) {
            notFound.classList.add("hidden");
        }


    } catch (error) {

        console.error(
            "Product loading error:",
            error
        );

        showProductNotFound(
            "We couldn't load this product. Please try again."
        );
    }
}


