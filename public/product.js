/* ============================================================
   SHOPIFY HELPER
   ============================================================ */

async function shopifyProductRequest(query, variables = {}) {

    const response = await fetch("/api/shopify", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
            query,
            variables
        })
    });

    if (!response.ok) {
        throw new Error(
            `Shopify request failed: ${response.status}`
        );
    }

    const json = await response.json();

    if (json.errors) {
        console.error("Shopify GraphQL errors:", json.errors);
        throw new Error(
            json.errors.map(error => error.message).join(", ")
        );
    }

    return json.data;
}


/* ============================================================
   LOAD PRODUCT FROM SHOPIFY
   ============================================================ */

async function getShopifyProduct({ handle = null, id = null } = {}) {

    let productQuery;
    let variables;

    /*
     * Support BOTH:
     *
     * product.html?handle=product-handle
     *
     * AND the links currently generated by shopify.js:
     *
     * product.html?id=gid://shopify/Product/123456789
     */

    if (handle) {
        handle = handle.trim().toLowerCase();

        productQuery = `
            product(handle: $handle) {
                id
                title
                handle
                description
                productType
                vendor
                tags

                collections(first: 10) {
                    edges {
                        node {
                            id
                            title
                            handle
                        }
                    }
                }

                featuredImage {
                    url
                    altText
                }

                images(first: 12) {
                    edges {
                        node {
                            url
                            altText
                        }
                    }
                }

                variants(first: 10) {
                    edges {
                        node {
                            id
                            title
                            sku
                            availableForSale

                            price {
                                amount
                                currencyCode
                            }

                            compareAtPrice {
                                amount
                                currencyCode
                            }

                            image {
                                url
                                altText
                            }
                        }
                    }
                }
            }
        `;

        variables = {
            handle
        };

    } else if (id) {

        productQuery = `
            product(id: $id) {
                id
                title
                handle
                description
                productType
                vendor
                tags

                collections(first: 10) {
                    edges {
                        node {
                            id
                            title
                            handle
                        }
                    }
                }

                featuredImage {
                    url
                    altText
                }

                images(first: 12) {
                    edges {
                        node {
                            url
                            altText
                        }
                    }
                }

                variants(first: 10) {
                    edges {
                        node {
                            id
                            title
                            sku
                            availableForSale

                            price {
                                amount
                                currencyCode
                            }

                            compareAtPrice {
                                amount
                                currencyCode
                            }

                            image {
                                url
                                altText
                            }
                        }
                    }
                }
            }
        `;

        variables = {
            id
        };

    } else {

        return null;
    }

    const query = `
        query GetProduct($${handle ? "handle: String!" : "id: ID!"}) {
            ${productQuery}
        }
    `;

    const data = await shopifyProductRequest(
        query,
        variables
    );

    return data.product;
}


/* ============================================================
   CONVERT SHOPIFY PRODUCT TO OUR PAGE FORMAT
   ============================================================ */

function normalizeShopifyProduct(product) {

    if (!product) {
        return null;
    }

    const variants = product.variants.edges.map(
        edge => edge.node
    );

    if (!variants.length) {
        return null;
    }

    /*
     * Your shopify.js currently uses the first variant.
     * We do the same here so the product page and shop page
     * stay consistent.
     */
    const variant = variants[0];

    const price = Number(variant.price.amount);

    const compareAtPrice =
        variant.compareAtPrice?.amount
            ? Number(variant.compareAtPrice.amount)
            : null;

    const hasDiscount =
        compareAtPrice !== null &&
        compareAtPrice > price;

    const discount =
        hasDiscount
            ? Math.round(
                (1 - price / compareAtPrice) * 100
            )
            : 0;

    const images =
        product.images.edges
            .map(edge => edge.node.url)
            .filter(Boolean);

    /*
     * Make sure the featured image is included.
     */
    if (
        product.featuredImage?.url &&
        !images.includes(product.featuredImage.url)
    ) {
        images.unshift(product.featuredImage.url);
    }

    /*
     * If Shopify has no images, use a local placeholder.
     */
    if (!images.length) {
        images.push("placeholder.png");
    }

    const collections =
        product.collections.edges.map(
            edge => edge.node
        );

    const category =
        collections[0]?.title ||
        product.productType ||
        "Shop";

    const categoryHandle =
        collections[0]?.handle || "";

    return {
        id: product.id,
        handle: product.handle,

        title: product.title,
        description: product.description || "",

        vendor: product.vendor || "",
        productType: product.productType || "",

        tags: product.tags || [],

        category,
        categoryHandle,

        price,
        compareAtPrice,
        hasDiscount,
        discount,

        available: variant.availableForSale,
        quantityAvailable:
            typeof variant.quantityAvailable === "number"
                ? variant.quantityAvailable
                : null,

        variantId: variant.id,
        variantTitle: variant.title,
        sku: variant.sku || "",

        images,

        variants
    };
}


function syncProductStockControls() {
    if (!CURRENT_PRODUCT) return;

    const stockLimit = typeof getKnownStockLimit === "function"
        ? getKnownStockLimit(CURRENT_PRODUCT.variantId)
        : null;
    const cartQuantity = typeof getCartVariantQuantity === "function"
        ? getCartVariantQuantity(CURRENT_PRODUCT.variantId)
        : 0;
    const remaining = stockLimit === null
        ? 99
        : Math.max(0, stockLimit - cartQuantity);
    const unavailable = !CURRENT_PRODUCT.available || remaining === 0;
    const input = document.getElementById("quantity-input");
    const decrease = document.getElementById("quantity-decrease");
    const increase = document.getElementById("quantity-increase");
    const addButton = document.getElementById("add-to-cart-btn");
    const buyButton = document.getElementById("buy-now-btn");

    if (input) {
        input.max = String(Math.max(1, remaining));
        if (remaining > 0) {
            input.value = String(Math.min(Number(input.value) || 1, remaining));
        }
        input.disabled = unavailable;
    }
    if (decrease) decrease.disabled = unavailable || Number(input?.value || 1) <= 1;
    if (increase) increase.disabled = unavailable || Number(input?.value || 1) >= remaining;
    if (addButton) addButton.disabled = unavailable;
    if (buyButton) buyButton.disabled = unavailable;
}


/* ============================================================
   PRODUCT PAGE RENDERING
   ============================================================ */

function renderProduct(product) {

    CURRENT_PRODUCT = product;
    PRODUCT_VARIANT_ID = product.variantId;
    PRODUCT_IMAGES = product.images;

    const wishlistButton = document.getElementById("wishlist-btn");
    const isSaved = window.isWishlistProductSaved?.(product.id) || false;
    wishlistButton?.classList.toggle("active", isSaved);
    const wishlistIcon = wishlistButton?.querySelector("i");
    if (wishlistIcon) {
        wishlistIcon.className = isSaved ? "fas fa-heart" : "far fa-heart";
    }

    document.title =
        `${product.title} — PixelBloxy`;

    /*
     * Main product information
     */

    const brand =
        document.getElementById("product-brand");

    const title =
        document.getElementById("product-title");

    const category =
        document.getElementById("product-category");

    if (brand) {
        brand.textContent =
            product.vendor ||
            product.category;
    }

    if (title) {
        title.textContent =
            product.title;
    }

    if (category) {
        category.textContent =
            product.category;
    }


    /*
     * Price
     */

    const price =
        document.getElementById("product-price");

    if (price) {
        price.textContent =
            `$${product.price.toFixed(2)}`;
    }


    /*
     * Compare-at price
     */

    const oldPrice =
        document.getElementById("product-old-price");

    const discount =
        document.getElementById("product-discount");

    if (
        product.hasDiscount &&
        product.compareAtPrice
    ) {

        if (oldPrice) {
            oldPrice.textContent =
                `$${product.compareAtPrice.toFixed(2)}`;

            oldPrice.classList.remove("hidden");
        }

        if (discount) {
            discount.textContent =
                `-${product.discount}%`;

            discount.classList.remove("hidden");
        }

    } else {

        if (oldPrice) {
            oldPrice.textContent = "";
            oldPrice.classList.add("hidden");
        }

        if (discount) {
            discount.textContent = "";
            discount.classList.add("hidden");
        }
    }


    /*
     * Availability
     */

    const availability =
        document.getElementById("product-availability");

    if (availability) {

        if (product.available) {

            availability.innerHTML = `
                <i class="fas fa-check-circle mr-1"></i>
                Available
            `;

            availability.className =
                "text-sm font-medium text-emerald-500";

        } else {

            availability.innerHTML = `
                <i class="fas fa-times-circle mr-1"></i>
                Sold Out
            `;

            availability.className =
                "text-sm font-medium text-red-500";
        }
    }


    /*
     * SKU
     */

    const sku =
        document.getElementById("product-sku");

    if (sku) {

        if (product.sku) {

            sku.textContent =
                `SKU: #${product.sku}`;

        } else {

            sku.textContent =
                "SKU: Not provided";
        }
    }


    /*
     * Short description
     */

    const description =
        document.getElementById("product-description");

    if (description) {
        description.textContent =
            product.description ||
            "No description available.";
    }


    /*
     * Full description
     */

    const fullDescription =
        document.getElementById("full-description");

    if (fullDescription) {

        if (product.description) {

            /*
             * Escape HTML before inserting Shopify text.
             * This prevents product descriptions from injecting HTML.
             */
            fullDescription.innerHTML =
                escapeHtml(product.description)
                    .replace(/\n/g, "<br>");

        } else {

            fullDescription.innerHTML =
                "<p>No additional description available.</p>";
        }
    }


    /*
     * Product type / tags as features
     */

    renderFeatures(product);


    /*
     * Specifications
     */

    renderSpecifications(product);


    /*
     * Reviews
     *
     * Your current Shopify query does not retrieve review data,
     * so we do not invent fake reviews.
     */

    renderReviews();


    /*
     * Set product variant for cart buttons
     */

    const addButton =
        document.getElementById("add-to-cart-btn");

    const buyButton =
        document.getElementById("buy-now-btn");

    if (addButton) {

        addButton.dataset.variantId =
            product.variantId;

        addButton.dataset.productId =
            product.id;

        addButton.disabled =
            !product.available;

        if (!product.available) {
            addButton.textContent =
                "Sold Out";
        }
    }

    if (buyButton) {

        buyButton.dataset.variantId =
            product.variantId;

        buyButton.dataset.productId =
            product.id;

        buyButton.disabled =
            !product.available;
    }

    syncProductStockControls();


    /*
     * Gallery
     */

    renderGallery(product);


    /*
     * Related products
     */

    renderRelatedProducts(product);
}


/* ============================================================
   FEATURES
   ============================================================ */

function renderFeatures(product) {

    const container =
        document.getElementById("features-list");

    if (!container) {
        return;
    }

    const features = [];

    if (product.productType) {
        features.push(
            `Type: ${product.productType}`
        );
    }

    if (product.category) {
        features.push(
            `Game: ${product.category}`
        );
    }

    if (product.variantTitle &&
        product.variantTitle !== "Default Title") {

        features.push(
            `Variant: ${product.variantTitle}`
        );
    }

    if (product.available) {
        features.push("Available for purchase");
    }

    if (product.tags?.length) {

        product.tags
            .slice(0, 5)
            .forEach(tag => {
                features.push(tag);
            });
    }

    if (!features.length) {

        container.innerHTML = `
            <li class="flex items-start">
                <i class="fas fa-check text-violet mr-2 mt-1 text-xs"></i>
                Product available from Shopify
            </li>
        `;

        return;
    }

    container.innerHTML =
        features.map(feature => `
            <li class="flex items-start">
                <i class="fas fa-check text-violet mr-2 mt-1 text-xs"></i>
                <span>${escapeHtml(feature)}</span>
            </li>
        `).join("");
}


/* ============================================================
   SPECIFICATIONS
   ============================================================ */

function renderSpecifications(product) {

    const table =
        document.getElementById("spec-table");

    if (!table) {
        return;
    }

    const specifications = [
        {
            label: "Game",
            value: product.category
        },
        {
            label: "Product Type",
            value:
                product.productType || "—"
        },
        {
            label: "Variant",
            value:
                product.variantTitle === "Default Title"
                    ? "Standard"
                    : product.variantTitle || "—"
        },
        {
            label: "Availability",
            value:
                product.available
                    ? "Available"
                    : "Sold Out"
        }
    ];

    if (product.sku) {
        specifications.push({
            label: "SKU",
            value: product.sku
        });
    }

    if (
        product.quantityAvailable !== null &&
        product.quantityAvailable !== undefined
    ) {
        specifications.push({
            label: "Quantity Available",
            value: String(product.quantityAvailable)
        });
    }

    table.innerHTML =
        specifications.map(spec => `
            <tr>
                <td>${escapeHtml(spec.label)}</td>
                <td>${escapeHtml(spec.value)}</td>
            </tr>
        `).join("");
}


